// 単項演算 (++/--，-/+/~/!，グローバル・ローカル変数)
int g = 10;
void main(void) {
    int x = 5;
    int a;
    a = ++x;        // 前置インクリメント (新値が式の値)
    a = x--;        // 後置デクリメント (旧値が式の値)
    ++g;            // グローバル変数の前置インクリメント (式文)
    g--;            // グローバル変数の後置デクリメント (式文)
    a = -x;         // 単項マイナス (符号反転)
    a = +x;         // 単項プラス (値そのもの)
    a = ~x;         // ビット反転
    a = !x;         // 論理否定
}
